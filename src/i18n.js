let initialLanguage = 'en';
try {
  const savedLanguage = window.localStorage.getItem(LANGUAGE_KEY);
  if (savedLanguage && Object.hasOwn(resources, savedLanguage)) initialLanguage = savedLanguage;
} catch (error) {
  console.warn('Could not read the saved public language:', error);
}

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLanguage,
    fallbackLng: 'en',
    supportedLngs: ['en', 'fr', 'es'],
    interpolation: { escapeValue: false },
    initImmediate: false,
  });

i18n.on('languageChanged', (language) => {
  const publicLanguage = ['en', 'fr', 'es'].includes(language) ? language : 'en';
  document.documentElement.lang = publicLanguage;
  try {
    window.localStorage.setItem(LANGUAGE_KEY, publicLanguage);
  } catch (error) {
    console.warn('Could not save the selected public language:', error);
  }
});

document.documentElement.lang = initialLanguage;

export default i18n;
